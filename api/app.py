"""REST API exposing the RAG.

Run it with:  uv run uvicorn api.app:app
Interactive documentation (Swagger UI): http://127.0.0.1:8000/docs
"""
import contextlib
import datetime
import logging
import secrets
import threading

import anthropic
from fastapi import (
    BackgroundTasks,
    Depends,
    FastAPI,
    Header,
    HTTPException,
    Request,
    status,
)
from pydantic import BaseModel, Field, field_validator
from sqlalchemy.exc import SQLAlchemyError

from api import rag
from api.dates import describe_periods
from config import settings
from scripts.vectorize import vectorize

logger = logging.getLogger(__name__)


def load_embedding_model():
    from FlagEmbedding import BGEM3FlagModel
    return BGEM3FlagModel("BAAI/bge-m3", use_fp16=False, devices="cpu")


@contextlib.asynccontextmanager
async def lifespan(app):
    # Loaded once at startup and shared by all the requests (loading it takes a while).
    app.state.embedding_model = load_embedding_model()
    app.state.rebuild = RebuildState()
    yield


app = FastAPI(
    title="Puls-Events RAG API",
    description="Recommends cultural events (OpenAgenda data) in answer to questions in natural language.",
    version="0.1.0",
    lifespan=lifespan,
)


# ---- Schemas ----

class AskRequest(BaseModel):
    question: str = Field(min_length=1, max_length=2000, examples=["Un concert de jazz à Lyon ce week-end"])

    @field_validator("question")
    @classmethod
    def not_blank(cls, value):
        value = value.strip()
        if not value:
            raise ValueError("the question must not be empty")
        return value


class RetrievedEvent(BaseModel):
    uid: int
    title: str
    city: str | None
    url: str | None
    score: float


class AskResponse(BaseModel):
    question: str
    answer: str
    periods: str = Field(description="Period(s) of interest the system understood from the question")
    events: list[RetrievedEvent] = Field(description="Candidate events given to the LLM, by relevance")


class RebuildRequest(BaseModel):
    reset: bool = Field(
        default=False,
        description="false: only vectorize the events that are not vectorized yet (resumes an interrupted run). "
                    "true: delete all the vectors and rebuild them from scratch (several hours, "
                    "/ask returns incomplete results meanwhile).",
    )


class RebuildStatus(BaseModel):
    running: bool
    reset: bool | None = None
    started_at: datetime.datetime | None = None
    finished_at: datetime.datetime | None = None
    error: str | None = None


# ---- Rebuild state ----

class RebuildState:
    def __init__(self):
        self.lock = threading.Lock()
        self.status = RebuildStatus(running=False)

    def try_start(self, reset):
        with self.lock:
            if self.status.running:
                return False
            self.status = RebuildStatus(running=True, reset=reset, started_at=datetime.datetime.now())
            return True

    def finish(self, error=None):
        with self.lock:
            self.status = self.status.model_copy(
                update={"running": False, "finished_at": datetime.datetime.now(), "error": error})


def rebuild_job(state, model, reset):
    try:
        vectorize(model, reset)
    except Exception as e:
        logger.exception("Rebuild failed")
        state.finish(error=f"{type(e).__name__}: {e}")
    else:
        state.finish()


def check_admin_token(x_admin_token: str | None = Header(default=None)):
    if settings.admin_token and not (x_admin_token and secrets.compare_digest(x_admin_token, settings.admin_token)):
        raise HTTPException(status.HTTP_401_UNAUTHORIZED, "Missing or invalid X-Admin-Token header")


# ---- Routes ----

@app.post("/ask", response_model=AskResponse, summary="Ask a question to the RAG")
def ask(body: AskRequest, request: Request):
    """Takes a question about cultural events and returns the answer generated by the LLM
    from the most relevant events of the period the question is about."""
    try:
        result = rag.answer(body.question, request.app.state.embedding_model)
    except anthropic.APIError as e:
        logger.exception("LLM call failed")
        raise HTTPException(status.HTTP_502_BAD_GATEWAY, f"The LLM call failed: {type(e).__name__}")
    except SQLAlchemyError as e:
        logger.exception("Database error")
        raise HTTPException(status.HTTP_503_SERVICE_UNAVAILABLE, f"Database error: {type(e).__name__}")

    scores = {uid: score for uid, _, _, score in result.results}
    return AskResponse(
        question=body.question,
        answer=result.answer,
        periods=describe_periods(result.periods),
        events=[
            RetrievedEvent(uid=event.uid, title=event.title_fr, city=event.location_city,
                           url=event.canonicalurl, score=scores.get(event.uid, 0.0))
            for event, _ in result.events
        ],
    )


@app.post(
    "/rebuild",
    response_model=RebuildStatus,
    status_code=status.HTTP_202_ACCEPTED,
    dependencies=[Depends(check_admin_token)],
    summary="Rebuild the vector index",
    responses={409: {"description": "A rebuild is already running"},
               401: {"description": "Missing or invalid X-Admin-Token (only when ADMIN_TOKEN is set)"}},
)
def rebuild(request: Request, background_tasks: BackgroundTasks, body: RebuildRequest | None = None):
    """Starts the vectorization of the events in the background (see scripts/vectorize.py) and returns
    immediately. Follow its progress with GET /rebuild."""
    reset = body.reset if body else False
    state = request.app.state.rebuild
    if not state.try_start(reset):
        raise HTTPException(status.HTTP_409_CONFLICT, "A rebuild is already running")
    background_tasks.add_task(rebuild_job, state, request.app.state.embedding_model, reset)
    return state.status


@app.get("/rebuild", response_model=RebuildStatus, summary="Status of the last rebuild")
def rebuild_status(request: Request):
    return request.app.state.rebuild.status


@app.get("/health", summary="Health check")
def health():
    return {"status": "ok"}
